/// What a byte-backed value is, which selects its codec.
#[derive(Clone, Copy, Debug, PartialEq, Eq, strum::IntoStaticStr)]
pub(crate) enum Role {
    #[strum(serialize = "public key")]
    PublicKey,
    #[strum(serialize = "secret key")]
    SecretKey,
    #[cfg(any(
        feature = "bird-of-prey",
        feature = "falcon",
        feature = "mayo",
        feature = "ml-dsa",
        feature = "slh-dsa",
        feature = "xmss"
    ))]
    #[strum(serialize = "signature")]
    Signature,
}

impl Role {
    /// The `key-type` attribute byte: 0 public, 1 secret.
    const fn key_type(self) -> u8 {
        match self {
            Self::SecretKey => 1,
            _ => 0,
        }
    }
}

/// The standard multicodecs of a scheme enum, generated by `multicodec_table!`.
pub(crate) trait SchemeCodec: Sized {
    /// The standard codec for this scheme in `role`, if bedrock's bytes match it.
    fn codec(self, role: Role) -> Option<Codec>;
    /// The scheme a standard codec names in `role`.
    fn from_codec(codec: Codec, role: Role) -> Option<Self>;
}

/// The codec a value is encoded with: its standard codec, or [`Codec::Identity`].
pub(crate) fn codec_of<T>(value: &T, role: Role) -> Codec
where
    T: RawBytes,
    T::Scheme: SchemeCodec,
{
    value.scheme().codec(role).unwrap_or(Codec::Identity)
}

/// Checks that `attributes` holds exactly the keys in `expected`.
fn expect_attributes<K, V>(attributes: &BTreeMap<K, V>, expected: &[K]) -> Result<()>
where
    K: Ord + std::fmt::Display,
{
    if attributes.len() == expected.len() && expected.iter().all(|k| attributes.contains_key(k)) {
        return Ok(());
    }
    let names = |keys: &mut dyn Iterator<Item = &K>| {
        keys.map(ToString::to_string).collect::<Vec<_>>().join(", ")
    };
    Err(MultiformatError::UnexpectedAttributes {
        expected: names(&mut expected.iter()),
        actual: names(&mut attributes.keys()),
    }
    .into())
}

/// Rejects the identity codec for a scheme that has a standard one, so each value has
/// exactly one encoding.
fn reject_standard<S: SchemeCodec + Copy + std::fmt::Display>(scheme: S, role: Role) -> Result<S> {
    match scheme.codec(role) {
        Some(_) => Err(MultiformatError::NonCanonicalIdentity(scheme.to_string()).into()),
        None => Ok(scheme),
    }
}

/// Decodes one complete value from binary input, rejecting trailing bytes and any
/// encoding other than the canonical one (for example, attributes out of order).
fn decode_exact<'a, T>(bytes: &'a [u8]) -> Result<T>
where
    T: TryDecodeFrom<'a>,
    for<'b> Vec<u8>: From<&'b T>,
    MultiformatError: From<T::Error>,
{
    let (value, rest) = T::try_decode_from(bytes).map_err(MultiformatError::from)?;
    if !rest.is_empty() {
        return Err(MultiformatError::TrailingBytes(rest.len()).into());
    }
    let canonical = Vec::<u8>::from(&value);
    let matches = canonical == bytes;
    #[cfg(feature = "zeroize")]
    {
        let mut canonical = canonical;
        zeroize::Zeroize::zeroize(&mut canonical);
    }
    if matches {
        Ok(value)
    } else {
        Err(MultiformatError::NonCanonical.into())
    }
}

/// Reads a whole multiformat value from a serde deserializer: the struct form in
/// human-readable formats, and exactly one binary encoding otherwise.
fn deserialize_exact<'de, T, D>(d: D) -> std::result::Result<T, D::Error>
where
    T: Deserialize<'de> + for<'a> TryDecodeFrom<'a>,
    for<'b> Vec<u8>: From<&'b T>,
    MultiformatError: for<'a> From<<T as TryDecodeFrom<'a>>::Error>,
    D: Deserializer<'de>,
{
    if d.is_human_readable() {
        T::deserialize(d)
    } else {
        let bytes = serdect::slice::deserialize_hex_or_bin_vec(d)?;
        let value = decode_exact::<T>(&bytes).map_err(serde::de::Error::custom);
        #[cfg(feature = "zeroize")]
        {
            let mut bytes = bytes;
            zeroize::Zeroize::zeroize(&mut bytes);
        }
        value
    }
}

/// Builds the Multikey for a key.
pub(crate) fn to_multikey<T>(value: &T, role: Role) -> Result<Multikey>
where
    T: RawBytes,
    T::Scheme: SchemeCodec,
{
    let scheme = value.scheme();
    let builder = match scheme.codec(role) {
        Some(codec) => multi_key::Builder::new(codec),
        None => multi_key::Builder::new(Codec::Identity)
            .with_algorithm_name(&scheme.to_string())
            .with_key_type(role.key_type()),
    };
    Ok(builder
        .with_key_bytes(value.as_ref())
        .try_build()
        .map_err(MultiformatError::from)?)
}

/// Reads a key out of a Multikey.
pub(crate) fn from_multikey<T>(mk: &Multikey, role: Role) -> Result<T>
where
    T: RawBytes,
    T::Scheme: SchemeCodec,
{
    use multi_key::AttrId;

    if !mk.comment.is_empty() {
        return Err(MultiformatError::Comment.into());
    }
    let codec = mk.codec();
    let scheme = if codec == Codec::Identity {
        expect_attributes(
            &mk.attributes,
            &[AttrId::KeyData, AttrId::AlgorithmName, AttrId::KeyType],
        )?;
        let name = mk
            .attributes
            .get(&AttrId::AlgorithmName)
            .map(|name| std::str::from_utf8(name))
            .and_then(std::result::Result::ok)
            .ok_or(MultiformatError::AlgorithmName)?;
        let key_type = mk.attributes.get(&AttrId::KeyType).map(|k| k.as_slice());
        if key_type != Some([role.key_type()].as_slice()) {
            return Err(MultiformatError::KeyType(role.into()).into());
        }
        reject_standard(name.parse::<T::Scheme>()?, role)?
    } else {
        expect_attributes(&mk.attributes, &[AttrId::KeyData])?;
        T::Scheme::from_codec(codec, role).ok_or(MultiformatError::UnexpectedCodec {
            codec,
            expected: role.into(),
        })?
    };
    let bytes = mk
        .attributes
        .get(&AttrId::KeyData)
        .map_or(&[][..], |bytes| bytes.as_slice());
    T::from_raw_bytes(scheme, bytes)
}

/// Builds the Multisig for a signature.
#[cfg(any(
    feature = "bird-of-prey",
    feature = "falcon",
    feature = "mayo",
    feature = "ml-dsa",
    feature = "slh-dsa",
    feature = "xmss"
))]
pub(crate) fn to_multisig<T>(value: &T) -> Result<Multisig>
where
    T: RawBytes,
    T::Scheme: SchemeCodec,
{
    let scheme = value.scheme();
    let builder = match scheme.codec(Role::Signature) {
        Some(codec) => multi_sig::Builder::new(codec),
        None => multi_sig::Builder::new(Codec::Identity).with_scheme(scheme.into()),
    };
    Ok(builder
        .with_signature_bytes(value)
        .try_build()
        .map_err(MultiformatError::from)?)
}

/// Reads a signature out of a Multisig.
#[cfg(any(
    feature = "bird-of-prey",
    feature = "falcon",
    feature = "mayo",
    feature = "ml-dsa",
    feature = "slh-dsa",
    feature = "xmss"
))]
pub(crate) fn from_multisig<T>(ms: &Multisig) -> Result<T>
where
    T: RawBytes,
    T::Scheme: SchemeCodec,
{
    use multi_sig::AttrId;

    if !ms.message.is_empty() {
        return Err(MultiformatError::Message.into());
    }
    let codec = ms.codec();
    let scheme = if codec == Codec::Identity {
        expect_attributes(&ms.attributes, &[AttrId::SigData, AttrId::Scheme])?;
        let raw = ms
            .attributes
            .get(&AttrId::Scheme)
            .map_or(&[][..], Vec::as_slice);
        let value = match Varuint::<u8>::try_decode_from(raw) {
            Ok((value, rest)) if rest.is_empty() && Vec::<u8>::from(Varuint(value.0)) == raw => {
                value.0
            }
            _ => return Err(MultiformatError::SchemeAttribute.into()),
        };
        reject_standard(T::Scheme::try_from(value)?, Role::Signature)?
    } else {
        expect_attributes(&ms.attributes, &[AttrId::SigData])?;
        T::Scheme::from_codec(codec, Role::Signature).ok_or(MultiformatError::UnexpectedCodec {
            codec,
            expected: Role::Signature.into(),
        })?
    };
    let bytes = ms
        .attributes
        .get(&AttrId::SigData)
        .map_or(&[][..], Vec::as_slice);
    T::from_raw_bytes(scheme, bytes)
}

/// Serializes a key as its Multikey.
pub(crate) fn serialize_key<T, S>(
    value: &T,
    role: Role,
    s: S,
) -> std::result::Result<S::Ok, S::Error>
where
    T: RawBytes,
    T::Scheme: SchemeCodec,
    S: Serializer,
{
    to_multikey(value, role)
        .map_err(serde::ser::Error::custom)?
        .serialize(s)
}

/// Deserializes a key from its Multikey.
pub(crate) fn deserialize_key<'de, T, D>(d: D, role: Role) -> std::result::Result<T, D::Error>
where
    T: RawBytes,
    T::Scheme: SchemeCodec,
    D: Deserializer<'de>,
{
    let mk = deserialize_exact::<Multikey, D>(d)?;
    from_multikey(&mk, role).map_err(serde::de::Error::custom)
}

/// Serializes a signature as its Multisig.
#[cfg(any(
    feature = "bird-of-prey",
    feature = "falcon",
    feature = "mayo",
    feature = "ml-dsa",
    feature = "slh-dsa",
    feature = "xmss"
))]
pub(crate) fn serialize_signature<T, S>(value: &T, s: S) -> std::result::Result<S::Ok, S::Error>
where
    T: RawBytes,
    T::Scheme: SchemeCodec,
    S: Serializer,
{
    to_multisig(value)
        .map_err(serde::ser::Error::custom)?
        .serialize(s)
}

/// Deserializes a signature from its Multisig.
#[cfg(any(
    feature = "bird-of-prey",
    feature = "falcon",
    feature = "mayo",
    feature = "ml-dsa",
    feature = "slh-dsa",
    feature = "xmss"
))]
pub(crate) fn deserialize_signature<'de, T, D>(d: D) -> std::result::Result<T, D::Error>
where
    T: RawBytes,
    T::Scheme: SchemeCodec,
    D: Deserializer<'de>,
{
    let ms = deserialize_exact::<Multisig, D>(d)?;
    from_multisig(&ms).map_err(serde::de::Error::custom)
}

#[cfg(all(test, feature = "ml-dsa", feature = "kgen", feature = "sign"))]
#[allow(clippy::unwrap_used, deprecated)]
mod tests {
    use super::*;
    use crate::{
        error::Error,
        ml_dsa::{MlDsaScheme, MlDsaSignature, MlDsaSigningKey, MlDsaVerificationKey},
    };
    use multi_key::AttrId as KeyAttr;
    use multi_sig::AttrId as SigAttr;

    struct Fixture {
        pk: MlDsaVerificationKey,
        sk: MlDsaSigningKey,
        sig: MlDsaSignature,
    }

    /// Generates a keypair for `scheme` and signs a fixed message with it.
    fn fixture(scheme: MlDsaScheme) -> Fixture {
        let (pk, sk) = scheme.keypair().unwrap();
        let sig = scheme.sign(b"envelope", &sk).unwrap();
        Fixture { pk, sk, sig }
    }

    /// Unwraps the error, failing the test unless it is a [`MultiformatError`].
    fn multiformat_err<T: std::fmt::Debug>(result: Result<T>) -> MultiformatError {
        match result {
            Err(Error::Multiformat(e)) => e,
            other => panic!("expected a multiformat error, got {other:?}"),
        }
    }

    #[test]
    fn rejects_comments_and_messages() {
        let Fixture { pk, sig, .. } = fixture(MlDsaScheme::Dsa65);
        let mut mk = Multikey::try_from(&pk).unwrap();
        mk.comment = "hello".into();
        assert!(matches!(
            multiformat_err(MlDsaVerificationKey::try_from(&mk)),
            MultiformatError::Comment
        ));
        let mut ms = Multisig::try_from(&sig).unwrap();
        ms.message = b"hello".to_vec();
        assert!(matches!(
            multiformat_err(MlDsaSignature::try_from(&ms)),
            MultiformatError::Message
        ));
    }

    #[test]
    fn rejects_missing_and_extra_attributes() {
        let Fixture { pk, sig, .. } = fixture(MlDsaScheme::Dsa65);
        let mut mk = Multikey::try_from(&pk).unwrap();
        mk.attributes.insert(KeyAttr::KeyType, vec![0].into());
        assert!(matches!(
            multiformat_err(MlDsaVerificationKey::try_from(&mk)),
            MultiformatError::UnexpectedAttributes { .. }
        ));
        mk.attributes.clear();
        assert!(matches!(
            multiformat_err(MlDsaVerificationKey::try_from(&mk)),
            MultiformatError::UnexpectedAttributes { .. }
        ));
        let mut ms = Multisig::try_from(&sig).unwrap();
        ms.attributes.insert(SigAttr::Scheme, vec![2]);
        assert!(matches!(
            multiformat_err(MlDsaSignature::try_from(&ms)),
            MultiformatError::UnexpectedAttributes { .. }
        ));
    }

    #[test]
    fn rejects_identity_for_a_standard_scheme() {
        let Fixture { pk, sig, .. } = fixture(MlDsaScheme::Dsa65);
        let mk = multi_key::Builder::new(Codec::Identity)
            .with_key_bytes(pk.as_ref())
            .with_algorithm_name("ML-DSA-65")
            .with_key_type(0)
            .try_build()
            .unwrap();
        assert!(matches!(
            multiformat_err(MlDsaVerificationKey::try_from(&mk)),
            MultiformatError::NonCanonicalIdentity(_)
        ));
        let ms = multi_sig::Builder::new(Codec::Identity)
            .with_signature_bytes(&sig)
            .with_scheme(MlDsaScheme::Dsa65.into())
            .try_build()
            .unwrap();
        assert!(matches!(
            multiformat_err(MlDsaSignature::try_from(&ms)),
            MultiformatError::NonCanonicalIdentity(_)
        ));
    }

    #[test]
    fn rejects_the_wrong_codec() {
        let Fixture { pk, sig, .. } = fixture(MlDsaScheme::Dsa65);
        let mk = Multikey::try_from(&pk).unwrap();
        assert!(matches!(
            multiformat_err(MlDsaSigningKey::try_from(&mk)),
            MultiformatError::UnexpectedCodec { .. }
        ));
        let ms = multi_sig::Builder::new(Codec::MlDsa87Msig)
            .with_signature_bytes(&sig)
            .try_build()
            .unwrap();
        // ML-DSA-87 signature length check rejects ML-DSA-65 bytes
        assert!(MlDsaSignature::try_from(&ms).is_err());
        let ms = multi_sig::Builder::new(Codec::FnDsa512Msig)
            .with_signature_bytes(&sig)
            .try_build()
            .unwrap();
        assert!(matches!(
            multiformat_err(MlDsaSignature::try_from(&ms)),
            MultiformatError::UnexpectedCodec { .. }
        ));
    }

    #[test]
    fn checks_identity_attributes() {
        let Fixture { pk, sk, sig } = fixture(MlDsaScheme::Dsa44);
        let mut mk = Multikey::try_from(&pk).unwrap();
        assert_eq!(mk.attributes[&KeyAttr::KeyType].as_slice(), &[0]);
        assert_eq!(
            Multikey::try_from(&sk).unwrap().attributes[&KeyAttr::KeyType].as_slice(),
            &[1]
        );
        mk.attributes.insert(KeyAttr::KeyType, vec![1].into());
        assert!(matches!(
            multiformat_err(MlDsaVerificationKey::try_from(&mk)),
            MultiformatError::KeyType(_)
        ));
        mk.attributes.insert(KeyAttr::KeyType, vec![0].into());
        mk.attributes
            .insert(KeyAttr::AlgorithmName, vec![0xff, 0xfe].into());
        assert!(matches!(
            multiformat_err(MlDsaVerificationKey::try_from(&mk)),
            MultiformatError::AlgorithmName
        ));
        mk.attributes
            .insert(KeyAttr::AlgorithmName, b"ML-DSA-13".to_vec().into());
        assert!(matches!(
            MlDsaVerificationKey::try_from(&mk),
            Err(Error::InvalidSchemeStr(_))
        ));
        mk.attributes
            .insert(KeyAttr::AlgorithmName, b"ML-DSA-44".to_vec().into());
        mk.attributes
            .insert(KeyAttr::KeyData, pk.as_ref()[1..].to_vec().into());
        assert!(matches!(
            MlDsaVerificationKey::try_from(&mk),
            Err(Error::MlDsaError(_))
        ));

        let mut ms = Multisig::try_from(&sig).unwrap();
        assert_eq!(ms.attributes[&SigAttr::Scheme].as_slice(), &[1]);
        // 1 as a two-byte varint is not minimal
        ms.attributes.insert(SigAttr::Scheme, vec![0x81, 0x00]);
        assert!(matches!(
            multiformat_err(MlDsaSignature::try_from(&ms)),
            MultiformatError::SchemeAttribute
        ));
        ms.attributes.insert(SigAttr::Scheme, vec![1, 0]);
        assert!(matches!(
            multiformat_err(MlDsaSignature::try_from(&ms)),
            MultiformatError::SchemeAttribute
        ));
        ms.attributes.insert(SigAttr::Scheme, vec![77]);
        assert!(matches!(
            MlDsaSignature::try_from(&ms),
            Err(Error::InvalidScheme(77))
        ));
    }

    #[test]
    fn rejects_attributes_out_of_order() {
        let Fixture { pk, .. } = fixture(MlDsaScheme::Dsa44);
        let mk = Multikey::try_from(&pk).unwrap();
        let canonical = Vec::<u8>::from(&mk);
        assert!(decode_exact::<Multikey>(&canonical).is_ok());
        // rebuild the same key with its three attributes written in reverse id order
        let mut reordered: Vec<u8> = Vec::from(multi_codec::Codec::Multikey);
        reordered.extend(Vec::<u8>::from(Codec::Identity));
        reordered.push(0); // empty comment
        reordered.push(3); // three attributes
        for (id, value) in mk.attributes.iter().rev() {
            reordered.push(id.code());
            reordered.extend(Vec::<u8>::from(Varuint(value.len())));
            reordered.extend_from_slice(value);
        }
        assert_eq!(Multikey::try_from(reordered.as_slice()).unwrap(), mk);
        assert!(matches!(
            decode_exact::<Multikey>(&reordered),
            Err(Error::Multiformat(MultiformatError::NonCanonical))
        ));
    }

    #[test]
    fn a_field_can_pick_either_encoding() {
        #[derive(Debug, PartialEq, Serialize, Deserialize)]
        struct Both {
            #[serde(with = "crate::multiformats")]
            multi: MlDsaVerificationKey,
            #[serde(with = "crate::plain")]
            plain: MlDsaVerificationKey,
            #[serde(with = "crate::multiformats")]
            signature: MlDsaSignature,
        }
        #[derive(Serialize)]
        struct Expected {
            multi: Multikey,
            plain: crate::plain::Plain<MlDsaVerificationKey>,
            signature: Multisig,
        }

        let Fixture { pk: multi, sig, .. } = fixture(MlDsaScheme::Dsa65);
        let Fixture { pk: plain, .. } = fixture(MlDsaScheme::Dsa87);
        let both = Both {
            multi,
            plain,
            signature: sig,
        };
        crate::test_utils::round_trip_all_formats(&both);
        let json = serde_json::to_value(&both).unwrap();
        let bytes = postcard::to_stdvec(&both).unwrap();
        let expected = Expected {
            multi: Multikey::try_from(&both.multi).unwrap(),
            signature: Multisig::try_from(&both.signature).unwrap(),
            plain: crate::plain::Plain(both.plain),
        };
        assert_eq!(json, serde_json::to_value(&expected).unwrap());
        assert_eq!(bytes, postcard::to_stdvec(&expected).unwrap());
    }

    #[test]
    fn rejects_trailing_bytes() {
        let Fixture { pk, .. } = fixture(MlDsaScheme::Dsa65);
        let mut bytes = Vec::<u8>::from(&Multikey::try_from(&pk).unwrap());
        bytes.extend_from_slice(&[1, 2, 3]);
        assert!(matches!(
            decode_exact::<Multikey>(&bytes),
            Err(Error::Multiformat(MultiformatError::TrailingBytes(3)))
        ));
    }
}
